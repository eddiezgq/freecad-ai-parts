def params(unit):
    p = PARAMS.get(unit)
    if not p:
        return None
    return {"beta": p[0], "eta_h": p[1], "mttr_min": p[2], "pm_h": p[3], "init_h": p[4], "modes": p[5]}


def cdf(t_h, beta, eta_h):
    return 1.0 - math.exp(-((max(0.0, t_h) / eta_h) ** beta))


def cond_fail(t0_h, dt_h, beta, eta_h):
    """已经运行 t0 小时没坏，再运行 dt 小时内坏掉的概率"""
    a, b = (max(0.0, t0_h) / eta_h) ** beta, (max(0.0, t0_h + dt_h) / eta_h) ** beta
    return 1.0 - math.exp(-(b - a))


def hazard(t_h, beta, eta_h):
    """失效率（每小时）"""
    return beta / eta_h * (max(t_h, 1e-6) / eta_h) ** (beta - 1)
